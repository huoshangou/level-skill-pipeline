// ─── Main ───────────────────────────────────────────────────────────────────

async function main() {
  const caseDir = process.argv[2];
  if (!caseDir) {
    console.error("用法: node render_gameplay_flow.js <case_dir>");
    process.exit(1);
  }

  const projectRoot = path.resolve(__dirname, "..");
  const casePath = path.resolve(projectRoot, caseDir);
  const htmlFile = path.join(casePath, "bubble_chart.html");
  const mmdFile = path.join(casePath, "bubble_chart.mmd");
  const svgFile = path.join(casePath, "bubble_chart_mermaid.svg");

  // 读取 IR
  const caseId = path.basename(casePath);
  const irPath = path.join(projectRoot, "test_cases", caseId, "ir_filled.json");
  if (!fs.existsSync(irPath)) {
    console.error(`找不到 IR: ${irPath}`);
    process.exit(1);
  }
  const irData = JSON.parse(fs.readFileSync(irPath, "utf-8"));

  if (!irData.FLOW || !irData.FLOW.nodes) {
    console.error("IR 缺少 FLOW.nodes");
    process.exit(1);
  }

  console.log(
    `读取 IR: ${irData.FLOW.nodes.length} 节点, ${irData.FLOW.edges.length} 边`
  );

  // 生成 .mmd
  const mmdContent = buildMermaid(irData.FLOW);
  fs.writeFileSync(mmdFile, mmdContent, "utf-8");
  console.log(`✓ 生成 Mermaid: ${mmdFile}`);

  // 调用 mmdc 渲染 SVG
  try {
    execSync(
      `mmdc -i "${mmdFile}" -o "${svgFile}" -t neutral -b transparent -w 1200`,
      { stdio: "pipe", timeout: 30000 }
    );
    console.log(`✓ mmdc 渲染: ${svgFile}`);
  } catch (err) {
    console.error(`mmdc 渲染失败: ${err.message}`);
    if (err.stderr) console.error(err.stderr.toString());
    process.exit(1);
  }

  // 读取 SVG
  let svgContent = fs.readFileSync(svgFile, "utf-8");
  // 移除 XML 声明和 doctype（如果有）
  svgContent = svgContent.replace(/<\?xml[^?]*\?>\s*/g, "");
  svgContent = svgContent.replace(/<!DOCTYPE[^>]*>\s*/g, "");

  // 组装 HTML
  const html = buildHtml(svgContent, irData, caseId);

  fs.writeFileSync(htmlFile, html, "utf-8");
  console.log(`✓ 输出: ${htmlFile}`);
}

main().catch((err) => {
  console.error("[ERR]", err);
  process.exit(1);
});
