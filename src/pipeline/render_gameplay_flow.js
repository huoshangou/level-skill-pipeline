#!/usr/bin/env node
/**
 * render_gameplay_flow.js  —  Mermaid 版玩法流程图渲染器
 *
 * 用法: node render_gameplay_flow.js <case_dir>
 * 示例: node render_gameplay_flow.js outputs/case_04_eavesdrop
 *
 * 步骤:
 * 1. 读取 IR (ir_filled.json) 的 FLOW 维度
 * 2. 将 IR.FLOW 转换为 Mermaid flowchart 语法 (.mmd)
 * 3. 调用 mmdc (Mermaid CLI) 渲染为 SVG
 * 4. 嵌入到 bubble_chart HTML 模板
 *
 * 依赖: mmdc (npm install -g @mermaid-js/mermaid-cli)
 */

const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

// ─── 功能类型着色（与 02_skill_router.md 一致） ─────────────────────────────

const NODE_CLASSES = {
  start:      { fill: "#F5F5F5", stroke: "#999",    name: "state_neutral" },
  end:        { fill: "#F5F5F5", stroke: "#999",    name: "state_neutral" },
  event:      { fill: "#F3E5F5", stroke: "#9C27B0", name: "event_trigger" },
  decision:   { fill: "#E8F5E9", stroke: "#4CAF50", name: "condition" },
  action:     { fill: "#FFF8E1", stroke: "#FF9800", name: "player_action" },
  cutscene:   { fill: "#E3F2FD", stroke: "#2196F3", name: "system_action" },
  dialogue:   { fill: "#E3F2FD", stroke: "#2196F3", name: "system_action" },
  failure:    { fill: "#FFF3E0", stroke: "#FF9800", name: "failure" },
  forced_exit:{ fill: "#FFEBEE", stroke: "#F44336", name: "forced_exit" },
};
const DEFAULT_CLASS = { fill: "#F5F5F5", stroke: "#999", name: "state_neutral" };

function xmlEscape(s) {
  if (!s) return "";
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
}

// ─── IR.FLOW → Mermaid .mmd ───────────────────────────────────────────────

function buildMermaid(flow) {
  const nodes = flow.nodes || [];
  const edges = flow.edges || [];

  let mmd = "flowchart TD\n";

  // classDef 定义
  const classDefSet = new Set();
  for (const [type, cls] of Object.entries(NODE_CLASSES)) {
    if (!classDefSet.has(cls.name)) {
      classDefSet.add(cls.name);
      mmd += `    classDef ${cls.name} fill:${cls.fill},stroke:${cls.stroke},stroke-width:1.5px,color:#111\n`;
    }
  }
  mmd += "\n";

  // 节点定义
  for (const node of nodes) {
    const cls = NODE_CLASSES[node.type] || DEFAULT_CLASS;
    const label = node.name || node.id;

    if (node.type === "start" || node.type === "end") {
      // stadium 形
      mmd += `    ${node.id}([${label}]):::${cls.name}\n`;
    } else if (node.type === "decision") {
      // 菱形
      mmd += `    ${node.id}{${label}}:::${cls.name}\n`;
    } else {
      // 矩形
      mmd += `    ${node.id}[${label}]:::${cls.name}\n`;
    }
  }
  mmd += "\n";

  // 边定义
  for (const edge of edges) {
    const label = edge.label || "";
    if (edge.type === "fail") {
      // 虚线箭头
      if (label) {
        mmd += `    ${edge.from} -.->|${label}| ${edge.to}\n`;
      } else {
        mmd += `    ${edge.from} -.-> ${edge.to}\n`;
      }
    } else if (edge.type === "optional") {
      // 虚线箭头
      if (label) {
        mmd += `    ${edge.from} -.->|${label}| ${edge.to}\n`;
      } else {
        mmd += `    ${edge.from} -.-> ${edge.to}\n`;
      }
    } else {
      // 实线箭头
      if (label) {
        mmd += `    ${edge.from} -->|${label}| ${edge.to}\n`;
      } else {
        mmd += `    ${edge.from} --> ${edge.to}\n`;
      }
    }
  }

  return mmd;
}

